const LOCALES = { pt: 'pt-BR', en: 'en-US', de: 'de-DE', es: 'es-ES', fr: 'fr-FR', it: 'it-IT' };

let currentLang = localStorage.getItem('lang') || 'pt';
if (!translations[currentLang]) currentLang = 'pt';

function t(key, vars) {
  let str = (translations[currentLang] || translations.pt)[key] ?? translations.pt[key] ?? key;
  if (vars) Object.entries(vars).forEach(([k, v]) => { str = str.replace(`{${k}}`, v); });
  return str;
}
function locale() { return LOCALES[currentLang] || 'pt-BR'; }
